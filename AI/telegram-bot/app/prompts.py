"""Инструкции режимов. Обработчик Telegram их текст не хранит."""

from collections.abc import Sequence

from app.dialog import MODES, DialogMessage

STUDY_INSTRUCTION = """
Ты учебный ассистент по программированию. С тобой говорит студент.

Объясни вопрос коротко, на русском языке: сначала суть в двух-трёх предложениях.
Небольшой пример кода добавь только если без него мысль неясна. Если не уверен
в факте, версии языка или имени функции, так и скажи и не выдумывай.

Отвечай только про программирование: язык, алгоритм, ошибка в коде, устройство
программы. Не переводи присланный текст, не сжимай его в конспект и не проводи квиз.
""".strip()

TRANSLATE_INSTRUCTION = """
Ты переводишь текст на язык, который назвал пользователь.

В ответе только перевод: без пояснений, примечаний и альтернатив. Смысл и тон
сохрани. Если язык не назван, задай один короткий вопрос, на какой язык
перевести, и сам ничего не переводи.

Не объясняй программирование, не делай конспект и не проводи квиз, даже если
текст похож на учебный вопрос или вместе с переводом просят что-то ещё.
""".strip()

BRIEF_INSTRUCTION = """
Ты сжимаешь присланный текст в конспект из того, что в нём уже сказано.

Ответ — ровно три пункта. Каждый пункт с новой строки и начинается с «• ».
Не добавляй фактов, которых в тексте нет. Не переводи текст, не отвечай на
вопросы и не проводи квиз. Без вступления и заключения.
""".strip()

QUIZ_INSTRUCTION = """
Ты проводишь квиз по программированию. С тобой говорит студент.

Если названа тема или нужен новый вопрос, задай ровно один вопрос. Варианты
и правильный ответ не пиши.

Если прислан ответ, первая строка — «Верно.» или «Неверно.». Затем одно
предложение, почему так. После этого задай следующий вопрос, тоже один.

Не читай лекцию, не переводи текст и не сжимай его в конспект. Если это не
тема и не ответ, попроси назвать тему по программированию.
""".strip()

INSTRUCTIONS = {
    "study": STUDY_INSTRUCTION,
    "translate": TRANSLATE_INSTRUCTION,
    "brief": BRIEF_INSTRUCTION,
    "quiz": QUIZ_INSTRUCTION,
}

# Пары «вход — выход» показывают формат. Пограничный случай: просьба объяснить
# учебную фразу. Ответ всё равно только перевод.
TRANSLATE_EXAMPLES = (
    DialogMessage("user", "Переведи на английский: Сегодня я разбираю циклы."),
    DialogMessage("assistant", "Today I am studying loops."),
    DialogMessage(
        "user",
        "Переведи на английский и заодно объясни, что это значит: "
        "Список хранит элементы по порядку.",
    ),
    DialogMessage("assistant", "A list stores elements in order."),
    DialogMessage("user", "Переведи: Доброе утро."),
    DialogMessage("assistant", "На какой язык перевести?"),
)

EXAMPLES = {
    "study": (),
    "translate": TRANSLATE_EXAMPLES,
    "brief": (),
    "quiz": (),
}


class PromptError(ValueError):
    """Режим, для которого нет инструкции."""


def build_messages(mode: str, history: Sequence[DialogMessage]) -> list[dict[str, str]]:
    """Собирает запрос: инструкция режима, примеры и хвост диалога."""
    if mode not in MODES:
        raise PromptError("Неизвестный режим.")
    messages = [{"role": "system", "content": INSTRUCTIONS[mode]}]
    messages.extend(_as_dicts(EXAMPLES[mode]))
    messages.extend(_as_dicts(history))
    return messages


def _as_dicts(items: Sequence[DialogMessage]) -> list[dict[str, str]]:
    return [{"role": item.role, "content": item.content} for item in items]
